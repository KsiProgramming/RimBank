using ArchUnitNET.Domain;

namespace RimBank.Architecture.Tests;

internal static class TypeFacts
{
    private static readonly HashSet<string> _generatedMarkers = new(StringComparer.Ordinal)
    {
        "System.Runtime.CompilerServices.CompilerGeneratedAttribute",
        "Microsoft.CodeAnalysis.EmbeddedAttribute",

        // Source generators, such as Aspire's Projects.* metadata in RimBank.AppHost (ADR 0014).
        "System.CodeDom.Compiler.GeneratedCodeAttribute",
    };

    public static string NamespaceName(this IType type) => type.Namespace?.FullName ?? string.Empty;

    /// <summary>Written by the compiler or a build tool (closures, state machines, embedded attributes, xUnit's entry point, source-generated types).</summary>
    public static bool IsToolGenerated(this IType type) =>
        type.IsCompilerGenerated
        || type.Name.StartsWith('<')
        || type.FullName.Contains("+<", StringComparison.Ordinal)
        || type.FullName.Contains("/<", StringComparison.Ordinal)
        || type.FullName == "Microsoft.CodeAnalysis.EmbeddedAttribute"
        || Namespaces.IsWithin(type.NamespaceName(), "Xunit.AutoGenerated")
        || type.NamespaceName().StartsWith("Xunit.AutoGenerated.", StringComparison.Ordinal)
        || type.Attributes.Any(attribute => _generatedMarkers.Contains(attribute.FullName));

    /// <summary>
    /// <paramref name="type"/> is, inherits from or implements the type named <paramref name="fullName"/>
    /// (a generic type is named in its open form, for example <c>RimBank.SharedKernel.IProjection`2</c>).
    /// </summary>
    public static bool IsAssignableTo(this IType type, string fullName)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var pending = new Stack<IType>([type]);
        while (pending.TryPop(out var current))
        {
            if (!seen.Add(current.FullName))
            {
                continue;
            }

            if (current.FullName == fullName)
            {
                return true;
            }

            foreach (var implemented in current.ImplementedInterfaces)
            {
                pending.Push(implemented);
            }

            if (current is Class { BaseClass: { } baseClass })
            {
                pending.Push(baseClass);
            }
        }

        return false;
    }

    /// <summary>The name used in messages: the full name, with <c>+</c> for nested types.</summary>
    public static string Display(this IType type) => type.FullName.Replace('/', '+');
}
